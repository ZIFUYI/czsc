#!/usr/bin/env python
"""Plot the full commodity universe versus a subset frozen from IS history coverage.

The historical filename is retained; no hard-coded eventual winners or invented
performance figures are displayed. Both curves use final signed-position ledgers.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import plotly.graph_objects as go

ROOT_DIR = Path(__file__).resolve().parents[2]
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from examples.multi_factor_cta.compare_50_vs_champion_universe import ARTIFACT_DIR, run_comparison  # noqa: E402


def render_universe_comparison(results: dict[str, Any]) -> go.Figure:
    """Render daily net curves generated by the common execution accountant."""
    fig = go.Figure()
    for universe, label in (("full_universe", "全资产池"), ("training_subset", "IS 历史覆盖子集")):
        for scheme, method in (("4_SecHRP_100%", "分层风险预算"), ("7_ActiveEC_100%", "动态预算")):
            daily = results[universe][scheme]["daily_returns"]
            fig.add_trace(go.Scatter(x=daily.index, y=1.0 + daily.cumsum(), name=f"{label} · {method}"))
    fig.update_layout(
        title="全资产池与 IS 历史覆盖子集：统一准入后的扣费研究曲线",
        xaxis_title="日期",
        yaxis_title="累计净值（固定名义本金）",
        template="plotly_white",
    )
    fig.add_annotation(
        text=f"子集选择截止：{results['selection_cutoff']}；资产数：{len(results['selected_symbols'])}",
        xref="paper",
        yref="paper",
        x=0,
        y=-0.2,
        showarrow=False,
    )
    return fig


def main() -> None:
    results = run_comparison()
    fig = render_universe_comparison(results)
    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    destination = ARTIFACT_DIR / "full_vs_training_subset.html"
    fig.write_html(destination, include_plotlyjs=True)
    (ARTIFACT_DIR / "full_vs_training_subset_symbols.json").write_text(
        json.dumps(results["selected_symbols"], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"已保存：{destination}")


if __name__ == "__main__":
    main()
